CREATE TABLE push_devices (
    push_device_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id) ON DELETE CASCADE,
    fid VARCHAR(128) NOT NULL UNIQUE,
    platform VARCHAR(10) NOT NULL CHECK (platform IN ('WEB', 'ANDROID', 'IOS')),
    registration_version UUID NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX ix_push_device_member ON push_devices(member_id);
